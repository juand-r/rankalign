def load_csv_data(filepath):
    """Load k-SAT data from a CSV file."""
    items = []
    with open(filepath, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            item = KSATItem(
                formula=row['formula'],
                assignment=row['assignment'],
                label=row['label'].strip().lower(),
                satisfying_assignment=row.get('satisfying_assignment', '')
            )
            items.append(item)
    return items


def load_data(seed=0, split_type='random', sample_negative=False, k=2, **kwargs):
    """
    Load and return train/test splits for k-SAT task.
    
    Args:
        seed: Random seed for shuffling
        split_type: Only 'random' is supported for this task
        sample_negative: Not used for this task (data already balanced)
        k: k value for k-SAT (2 for 2-SAT, 3 for 3-SAT)
    
    Returns:
        L_train, L_test: Lists of KSATItem namedtuples
    """
    # Find data directory
    data_dir = os.path.join(_parent_dir, '..', 'data')
    
    train_file = os.path.join(data_dir, f'{k}sat_train.csv')
    test_file = os.path.join(data_dir, f'{k}sat_test.csv')
    
    if not os.path.exists(train_file):
        raise FileNotFoundError(
            f"Training data not found: {train_file}\n"
            f"Run: python scripts/generate_ksat_data.py --k {k}"
        )
    if not os.path.exists(test_file):
        raise FileNotFoundError(
            f"Test data not found: {test_file}\n"
            f"Run: python scripts/generate_ksat_data.py --k {k}"
        )
    
    L_train = load_csv_data(train_file)
    L_test = load_csv_data(test_file)
    
    # Shuffle with seed
    random.seed(seed)
    random.shuffle(L_train)
    random.shuffle(L_test)
    
    print(f"Loaded {k}-SAT data: {len(L_train)} train, {len(L_test)} test")
    
    return L_train, L_test


