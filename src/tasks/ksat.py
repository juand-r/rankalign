def make_generator_prompt_zero_shot(item):
    """
    Zero-shot generator prompt: Given formula, produce satisfying assignment.
    """
    prompt = (
        f"Given the following Boolean formula in CNF (conjunctive normal form):\n"
        f"{item.formula}\n\n"
        f"Provide a variable assignment that satisfies this formula.\n"
        f"Assignment:"
    )
    return prompt


def detect_n_vars(assignment_str):
    """Detect number of variables from assignment string like 'x0=1, x1=0, x2=0, x3=0'."""
    # Count comma-separated parts
    return len(assignment_str.split(', '))


def make_generator_prompt_few_shot(item, k=2, n_vars=None):
    """
    Few-shot generator prompt with examples.
    """
    # Auto-detect n_vars from item if not provided
    if n_vars is None:
        n_vars = detect_n_vars(item.assignment)
    
    examples = get_few_shot_examples(k, n_vars)
    
    # Filter to only positive examples for generator
    positive_examples = [ex for ex in examples if ex['label'] == 'yes']
    
    prompt = "Given a Boolean formula in CNF, provide a variable assignment that satisfies it.\n\n"
    
    for i, ex in enumerate(positive_examples[:2]):
        prompt += f"Formula: {ex['formula']}\n"
        prompt += f"Assignment: {ex['assignment']}\n\n"
    
    prompt += f"Formula: {item.formula}\n"
    prompt += "Assignment:"
    
    return prompt


def make_discriminator_prompt_zero_shot(item, gen_response=None):
    """
    Zero-shot discriminator prompt: Does assignment satisfy formula?
    
    Args:
        item: KSATItem with formula
        gen_response: The assignment to validate (if None, uses item.assignment)
    """
    assignment = gen_response if gen_response else item.assignment
    
    prompt = (
        f"Given the Boolean formula in CNF:\n"
        f"{item.formula}\n\n"
        f"Does the variable assignment \"{assignment}\" satisfy this formula?\n"
        f"Answer with Yes or No.\n"
        f"Answer:"
    )
    return prompt


def make_discriminator_prompt_few_shot(item, gen_response=None, k=2, n_vars=None):
    """
    Few-shot discriminator prompt with examples.
    """
    assignment = gen_response if gen_response else item.assignment
    
    # Auto-detect n_vars from item if not provided
    if n_vars is None:
        n_vars = detect_n_vars(item.assignment)
    
    examples = get_few_shot_examples(k, n_vars)
    
    prompt = (
        "Determine if a variable assignment satisfies a Boolean formula in CNF.\n"
        "Answer with Yes or No.\n\n"
    )
    
    for ex in examples[:4]:
        answer = "Yes" if ex['label'] == 'yes' else "No"
        prompt += f"Formula: {ex['formula']}\n"
        prompt += f"Assignment: {ex['assignment']}\n"
        prompt += f"Answer: {answer}\n\n"
    
    prompt += f"Formula: {item.formula}\n"
    prompt += f"Assignment: {assignment}\n"
    prompt += "Answer:"
    
    return prompt


def get_completion(item):
    """
    Get the generator completion (the satisfying assignment).
    
    For the generator task, this is the correct answer to produce.
    We use the satisfying_assignment if available, otherwise the assignment.
    """
    if item.satisfying_assignment:
        return " " + item.satisfying_assignment
    return " " + item.assignment


def get_label(item):
    """
    Get the ground truth label ('yes' or 'no').
    
    Indicates whether the assignment satisfies the formula.
    """
    return item.label.strip().lower()


def make_prompt(item, style='generator', shots='zero', gen_response=None, neg=False, variation=0, k=2, n_vars=None, **kwargs):
    """
    Create prompt for generator or discriminator.
    
    Args:
        item: KSATItem namedtuple
        style: 'generator' or 'discriminator'
        shots: 'zero' or 'few'
        gen_response: For discriminator, the assignment to validate
        neg: Not used for this task
        variation: Prompt variation (for future use)
        k: k value for k-SAT (affects few-shot examples)
        n_vars: Number of variables (auto-detected from item if None)
    
    Returns:
        PromptCompletion namedtuple with .prompt and .completion
    """
    if style == 'generator':
        if shots == 'zero':
            prompt = make_generator_prompt_zero_shot(item)
        else:
            prompt = make_generator_prompt_few_shot(item, k=k, n_vars=n_vars)
        # Generator completion is the satisfying assignment
        completion = get_completion(item)
        return PromptCompletion(prompt=prompt, completion=completion)
    else:  # discriminator
        if shots == 'zero':
            prompt = make_discriminator_prompt_zero_shot(item, gen_response)
        else:
            prompt = make_discriminator_prompt_few_shot(item, gen_response, k=k, n_vars=n_vars)
        # Discriminator completion is Yes or No
        label = get_label(item)
        completion = " Yes" if label == 'yes' else " No"
        return PromptCompletion(prompt=prompt, completion=completion)


